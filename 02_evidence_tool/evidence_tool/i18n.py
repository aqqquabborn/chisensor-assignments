"""English / Simplified Chinese text for everything the tool generates.

    set_lang("zh"); t("issue.event.duplicate_conflict", eid="E00002")

Config texts (priorities.json, experiments.json) carry their own {"en": …, "zh": …}
pairs and are resolved by localize(). Source records (feedback CSV) are never translated.
"""
from __future__ import annotations

LANGS = ("en", "zh")
_lang = "en"


def set_lang(lang: str):
    global _lang
    if lang not in LANGS:
        raise ValueError(f"Unknown language {lang!r}; use one of {', '.join(LANGS)}")
    _lang = lang


def get_lang() -> str:
    return _lang


def t(key: str, **kw) -> str:
    """Translate; a missing key is a bug, so it raises instead of leaking the key into a report."""
    return STRINGS[_lang][key].format(**kw)


def tn(key: str, n: int, **kw) -> str:
    """Pluralised: uses key.1 for n == 1, key.n otherwise (Chinese has one form for both)."""
    return t(f"{key}.{'1' if n == 1 else 'n'}", n=n, **kw)


def join(items) -> str:
    return t("sep.list").join(items)


def localize(obj, lang: str | None = None):
    """Resolve every {"en": …, "zh": …} pair in a config tree to one language (falls back to English)."""
    lang = lang or _lang
    if isinstance(obj, dict):
        if set(obj) and set(obj) <= set(LANGS) and "en" in obj:
            return obj.get(lang) or obj["en"]
        return {k: localize(v, lang) for k, v in obj.items()}
    if isinstance(obj, list):
        return [localize(v, lang) for v in obj]
    return obj


